//! Regenerates `docs/benchmarks/baseline.svg` and `docs/benchmarks/baseline.md`
//! from `bench/baseline.json` (`mothergod_bench::graph`, `research/JOURNAL.md`
//! S2-D1's remaining "progress-graph rendering" line). Not yet wired into a
//! scheduled workflow — that needs `GH_ADMIN_TOKEN`, same as the CI baseline
//! gate (`research/JOURNAL.md` S2-A35); run by hand until it is: `cargo run
//! -p mothergod-bench --release --bin render_baseline_graph`, then `cargo x
//! fmt -- docs/benchmarks/baseline.svg` to pick up the canonical SVG
//! indentation `cargo x fmt --check` expects (this binary doesn't reproduce
//! it byte-for-byte, same as `site/status-data.json`'s own generate-then-fmt
//! step).

use mothergod_bench::baseline::parse_baseline;
use mothergod_bench::graph::{Bar, render_svg, render_table_markdown};
use std::path::PathBuf;
use std::process::{Command, ExitCode};

/// The workspace root, located relative to this crate's manifest so the
/// result is correct regardless of the caller's working directory.
fn repo_root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .expect("bench/Cargo.toml has a parent directory (the workspace root)")
        .to_path_buf()
}

fn main() -> ExitCode {
    let root = repo_root();

    let baseline_text = match std::fs::read_to_string(root.join("bench/baseline.json")) {
        Ok(text) => text,
        Err(err) => {
            eprintln!("failed to read bench/baseline.json: {err}");
            return ExitCode::FAILURE;
        }
    };
    let baseline = match parse_baseline(&baseline_text) {
        Ok(baseline) => baseline,
        Err(err) => {
            eprintln!("{err}");
            return ExitCode::FAILURE;
        }
    };
    let bars: Vec<Bar> = baseline
        .into_iter()
        .map(|(name, bits_per_byte)| Bar {
            name,
            bits_per_byte,
        })
        .collect();

    let generated_at = match Command::new("date")
        .args(["-u", "+%Y-%m-%dT%H:%M:%SZ"])
        .output()
    {
        Ok(output) if output.status.success() => {
            String::from_utf8_lossy(&output.stdout).trim().to_string()
        }
        Ok(output) => {
            eprintln!("date -u exited {}", output.status);
            return ExitCode::FAILURE;
        }
        Err(err) => {
            eprintln!("failed to run date -u: {err}");
            return ExitCode::FAILURE;
        }
    };

    let subtitle = format!(
        "as of {generated_at} \u{2014} own generator corpus (bench/baseline.json, research/JOURNAL.md S2-A35), not Silesia/Canterbury"
    );
    let svg = render_svg(
        "mothergod bits/byte on the fixed baseline cases",
        &subtitle,
        &bars,
    );

    let benchmarks_dir = root.join("docs/benchmarks");
    if let Err(err) = std::fs::create_dir_all(&benchmarks_dir) {
        eprintln!("failed to create {}: {err}", benchmarks_dir.display());
        return ExitCode::FAILURE;
    }

    let svg_path = benchmarks_dir.join("baseline.svg");
    if let Err(err) = std::fs::write(&svg_path, &svg) {
        eprintln!("failed to write {}: {err}", svg_path.display());
        return ExitCode::FAILURE;
    }

    let md = format!(
        "<!-- Generated by `cargo run -p mothergod-bench --release --bin \
         render_baseline_graph`. Do not hand-edit; re-run the generator instead. -->\n\n\
         # Baseline snapshot\n\n\
         As of {generated_at}. Source: `bench/baseline.json`, measured by \
         `mothergod::compress` on 11 fixed-seed, 50,000-byte cases \
         (`research/JOURNAL.md` S2-A35) — mothergod's own generator corpus, not the \
         pinned Silesia/Canterbury held-out finals. No gzip/zstd/xz comparison here: \
         this table is mothergod against itself, run over run; see \
         `docs/benchmarks/canterbury.md` for real numbers against the pinned \
         reference compressors on the Canterbury held-out final \
         (`research/JOURNAL.md` S2-A37).\n\n\
         ![Bar chart of mothergod bits/byte per baseline case, sorted ascending, as of {generated_at}](baseline.svg)\n\n\
         {}",
        render_table_markdown(&bars)
    );
    let md_path = benchmarks_dir.join("baseline.md");
    if let Err(err) = std::fs::write(&md_path, &md) {
        eprintln!("failed to write {}: {err}", md_path.display());
        return ExitCode::FAILURE;
    }

    println!("wrote {} and {}", svg_path.display(), md_path.display());
    ExitCode::SUCCESS
}
