//! Answers S1-P6's remaining open branch (`research/JOURNAL.md` S2-A88,
//! issue #447) before any integration code gets written: is the
//! LZ-preserving fast path even bit-cost-plausible?
//!
//! S2-A81 through S2-A88 measured a whole-buffer order-0 tANS coder with no
//! match stage and parked it, negative, as an automatic `Method` candidate:
//! it loses to the champion on 9 of 10 realistic buffers because it throws
//! away the redundancy elimination `Method::Lz`'s matches already provide.
//! S2-A88 named the one untried branch left: keep LZ matching, swap only
//! the *literal* entropy stage to tANS. This binary measures that branch
//! directly, on the literal-byte stream a real optimal parse actually
//! produces, instead of building the integration first and finding out
//! after.
//!
//! For each buffer: run [`mothergod::lz::parse_optimal`] to get the real
//! token stream, walk it exactly as [`mothergod::codec`]'s own
//! `walk_tokens` does (`Context::after_literal`/`after_copy`, same order),
//! and split the walk in two comparable costs over the literal bytes alone:
//!
//! - the champion's real per-literal cost, [`mothergod::literal::Literal`]'s
//!   context-mixing model via `ideal_cost_bits_sse` (the ideal-cost
//!   counterpart to the `encode_sse` path `Method::Lz` actually codes
//!   literals through for every non-`Transpose` candidate);
//! - an order-0 static tANS coder's cost on the same literal-byte stream in
//!   the same order, freq-table bytes charged in (same accounting S2-A87/
//!   S2-A88 used for the whole-buffer case).
//!
//! This does not build or wire a `Method`. It answers whether the
//! literal-only slice of the frame is close enough between the two coders
//! to justify the larger integration (`FORMAT_VERSION` bump, `Method`
//! variant, decoder support) S2-A88 flagged as a materially bigger
//! undertaking than any slice so far.
//!
//! Usage: `cargo run -p mothergod-bench --release --bin
//! tans_literal_measure`, run by hand like `tans_measure`, not wired into
//! CI.

use mothergod::literal::{Context, Literal};
use mothergod::lz::{self, Token};
use mothergod::tans;
use mothergod_bench::{
    access_log, base64_wrapped, entropy_ladder, gradient_image, interleaved_audio16, json_records,
    markov_h8_2_trap, sealed_seed, sqlite_like_records, x86_dense_code,
};

/// Sample size for every generated buffer, matching `tans_measure`'s own
/// convention (`research/JOURNAL.md` S2-A1).
const SAMPLE_LEN: usize = 200_000;

/// Seed for every generated buffer, matching `tans_measure`'s own
/// convention.
const SEED: u64 = 0xC0FF_EE12_3456_789A;

/// tANS table size, matching `tans_measure`'s own convention.
const TABLE_LOG2: u32 = 10;

/// One buffer to measure, named for the report.
struct Case {
    /// Label printed in the report.
    name: &'static str,
    /// The generated bytes.
    data: Vec<u8>,
}

/// Every buffer this binary measures, the same set and seeding rule
/// `tans_measure::cases` uses (`research/corpus/POLICY.md`'s sealed-seed
/// rule for the two sealed-only `DatasetKind`s): a buffer this measurement
/// tunes an implementation decision against must not be the sealed set
/// itself.
fn cases() -> Vec<Case> {
    vec![
        Case {
            name: "entropy_ladder(h=2)",
            data: entropy_ladder(2, SAMPLE_LEN, SEED),
        },
        Case {
            name: "entropy_ladder(h=6)",
            data: entropy_ladder(6, SAMPLE_LEN, SEED),
        },
        Case {
            name: "markov_h8_2_trap",
            data: markov_h8_2_trap(SAMPLE_LEN, SEED),
        },
        Case {
            name: "access_log (sealed)",
            data: access_log(SAMPLE_LEN, sealed_seed(SEED)),
        },
        Case {
            name: "json_records",
            data: json_records(SAMPLE_LEN, SEED),
        },
        Case {
            name: "base64_wrapped",
            data: base64_wrapped(SAMPLE_LEN, SEED),
        },
        Case {
            name: "interleaved_audio16",
            data: interleaved_audio16(SAMPLE_LEN, SEED),
        },
        Case {
            name: "gradient_image (sealed)",
            data: gradient_image(SAMPLE_LEN, sealed_seed(SEED)),
        },
        Case {
            name: "sqlite_like_records",
            data: sqlite_like_records(SAMPLE_LEN, SEED),
        },
        Case {
            name: "x86_dense_code",
            data: x86_dense_code(SAMPLE_LEN, SEED),
        },
    ]
}

/// Builds a 256-entry byte histogram, [`tans::normalize_frequencies`]'s
/// expected input shape for a byte alphabet.
fn byte_histogram(data: &[u8]) -> [u32; 256] {
    let mut counts = [0u32; 256];
    for &b in data {
        counts[usize::from(b)] += 1;
    }
    counts
}

/// Walks `data`'s real optimal parse in coding order, exactly as
/// `mothergod::codec`'s private `walk_tokens` does
/// (`Context::after_literal`/`after_copy`, flags/lengths/offsets skipped
/// since this measurement only prices the literal sub-stream), and returns
/// the literal bytes in coding order plus the champion's real per-literal
/// ideal cost summed over them (`Literal::ideal_cost_bits_sse`, the
/// `encode_sse` path every non-`Transpose` candidate codes literals
/// through).
fn literal_stream_and_champion_bits(data: &[u8]) -> (Vec<u8>, f64) {
    let tokens = lz::parse_optimal(data);
    let mut context = Context::default();
    let mut pos = 0usize;
    let mut model = Literal::new();
    let mut literal_bytes = Vec::new();
    let mut champion_bits = 0.0f64;

    for token in &tokens {
        match *token {
            Token::Literal(byte) => {
                champion_bits += model.ideal_cost_bits_sse(context, byte);
                literal_bytes.push(byte);
                context = context.after_literal(byte);
                pos += 1;
            }
            Token::Match { len, .. } | Token::Rep { len, .. } => {
                let end = pos + len as usize;
                context = context.after_copy(&data[pos..end]);
                pos = end;
            }
        }
    }
    (literal_bytes, champion_bits)
}

/// An order-0 static tANS coder's total bit cost on `literal_bytes`,
/// freq-table bytes charged in (S2-A87/S2-A88's accounting: a real decoder
/// needs the table on the wire, so leaving it uncharged understates the
/// real cost). `None` when `literal_bytes` is empty: `normalize_frequencies`
/// has no defined behavior over an all-zero histogram, and an all-match
/// parse leaves nothing for either coder to price.
#[allow(
    clippy::cast_precision_loss,
    reason = "frame_bytes stays far below 2^53 (a single measurement buffer here is 200,000 bytes)"
)]
fn tans_literal_bits(literal_bytes: &[u8]) -> Option<f64> {
    if literal_bytes.is_empty() {
        return None;
    }
    let counts = byte_histogram(literal_bytes);
    let freq = tans::normalize_frequencies(&counts, TABLE_LOG2);
    let table_symbol = tans::spread_symbols(&freq, TABLE_LOG2);
    let decode_table = tans::build_decode_table(&table_symbol, &freq, TABLE_LOG2);
    let encode_table = tans::build_encode_table(&table_symbol, &freq, TABLE_LOG2);

    let symbols: Vec<u32> = literal_bytes.iter().copied().map(u32::from).collect();
    let (tans_bytes, initial_state) = tans::encode_message(&symbols, &encode_table, &decode_table);
    let decoded = tans::decode_message(&tans_bytes, initial_state, symbols.len(), &decode_table);
    assert_eq!(
        decoded, symbols,
        "tANS round trip over the literal-byte stream must be exact"
    );

    let freq_table_bytes = tans::write_freq_table(&freq, TABLE_LOG2);
    let frame_bytes = tans_bytes.len() + freq_table_bytes.len();
    Some(frame_bytes as f64 * 8.0)
}

/// One buffer's full measurement.
struct Measurement {
    /// [`Case::name`].
    name: &'static str,
    /// Buffer length in bytes.
    len: usize,
    /// How many of `len` bytes the real optimal parse left as literals.
    literal_count: usize,
    /// The champion's real per-literal ideal cost, summed
    /// (`ideal_cost_bits_sse`).
    champion_literal_bits: f64,
    /// An order-0 static tANS coder's cost on the same literal-byte
    /// stream, freq table included. `None` when there were no literals.
    tans_literal_bits: Option<f64>,
}

fn measure(case: &Case) -> Measurement {
    let (literal_bytes, champion_literal_bits) = literal_stream_and_champion_bits(&case.data);
    let tans_literal_bits = tans_literal_bits(&literal_bytes);
    Measurement {
        name: case.name,
        len: case.data.len(),
        literal_count: literal_bytes.len(),
        champion_literal_bits,
        tans_literal_bits,
    }
}

#[allow(
    clippy::cast_precision_loss,
    reason = "byte and bit counts here stay far below 2^53"
)]
fn report(m: &Measurement) {
    let literal_fraction = m.literal_count as f64 / m.len as f64 * 100.0;
    println!(
        "=== {} ({} bytes, {} literals, {:.1}% of buffer) ===",
        m.name, m.len, m.literal_count, literal_fraction
    );
    match m.tans_literal_bits {
        None => println!("  no literals in this buffer's optimal parse; nothing to compare\n"),
        Some(tans_bits) => {
            let champion_bpl = m.champion_literal_bits / m.literal_count as f64;
            let tans_bpl = tans_bits / m.literal_count as f64;
            let delta_bytes_whole_frame = (tans_bits - m.champion_literal_bits) / 8.0;
            println!(
                "  bits/literal-byte: champion {champion_bpl:.4}  |  tANS {tans_bpl:.4}  (gap {:+.4})",
                tans_bpl - champion_bpl
            );
            println!(
                "  estimated frame-size delta from swapping only literal coding to tANS: {delta_bytes_whole_frame:+.1} bytes ({:+.4} bits/byte of the whole buffer)",
                (tans_bits - m.champion_literal_bits) / m.len as f64
            );
            println!();
        }
    }
}

fn main() {
    println!(
        "tANS literal-only measurement (research/JOURNAL.md S2-A88, issue #447); \
         sample_len={SAMPLE_LEN}, seed={SEED:#x}, table_log2={TABLE_LOG2}\n"
    );
    let measurements: Vec<Measurement> = cases().iter().map(measure).collect();
    for m in &measurements {
        report(m);
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use mothergod_bench::DatasetKind;

    #[test]
    fn cases_cover_every_dataset_kind() {
        assert_eq!(cases().len(), DatasetKind::ALL.len() + 1);
    }

    #[test]
    fn literal_stream_and_champion_bits_extracts_every_literal_in_order() {
        // A buffer with no repeats at all must parse to all literals: the
        // extracted stream should equal the input exactly, in order.
        let data = b"the quick brown fox jumps over a lazy dog, once";
        let (literal_bytes, champion_bits) = literal_stream_and_champion_bits(data);
        assert_eq!(literal_bytes, data);
        assert!(champion_bits > 0.0);
    }

    #[test]
    fn literal_stream_is_empty_on_a_long_run_of_one_byte() {
        // A long run of one byte parses almost entirely to matches; the
        // handful of leading literals a parser needs before it has a
        // source to match against is the only content this should report.
        let data = vec![b'x'; 10_000];
        let (literal_bytes, _) = literal_stream_and_champion_bits(&data);
        assert!(
            literal_bytes.len() < 10,
            "expected only a few leading literals, got {}",
            literal_bytes.len()
        );
    }

    #[test]
    fn tans_literal_bits_is_none_for_an_empty_stream() {
        assert_eq!(tans_literal_bits(&[]), None);
    }

    #[test]
    fn tans_literal_bits_round_trips_and_is_positive_for_a_real_stream() {
        let data = entropy_ladder(2, SAMPLE_LEN, SEED);
        let (literal_bytes, _) = literal_stream_and_champion_bits(&data);
        let bits = tans_literal_bits(&literal_bytes).expect("iid noise parses to many literals");
        assert!(bits > 0.0);
    }
}
